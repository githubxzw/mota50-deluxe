if __name__ == '__main__':
    import json
    data = open(os.path.join(ROOT, 'mota-data.js'), encoding='utf-8').read()
    import re
    m = re.search(r'"npcs":\{[^}]*\}', data)
    idx = json.loads('{'+m.group(0)+'}')['npcs']
    atlas = Image.open(os.path.join(OUT, 'npcs.png')).convert('RGBA')
    cell = 96
    rows = atlas.height // cell      # 28
    cols = atlas.width // cell       # 2
    for name, im32 in CELLS.items():
        i = idx[name]
        col, row = i // rows, i % rows
        hd = GA.enhance_cell(im32, 3)
        atlas.paste(hd, (col * cell, row * cell))
        print('重绘 NPC:', name, '→ 格子', (col, row))
    atlas.save(os.path.join(OUT, 'npcs.png'))
    q = atlas.quantize(colors=256, method=Image.FASTOCTREE)
    q.save(os.path.join(OUT, 'npcs.png'), optimize=True)
    # 预览
    prev = Image.new('RGBA', (len(CELLS) * 100, 108), (34, 36, 52, 255))
    for i, name in enumerate(CELLS):
        i2 = idx[name]
        c, r = i2 // rows, i2 % rows
        prev.alpha_composite(atlas.crop((c * cell, r * cell, c * cell + cell, r * cell + cell)),
                             (i * 100 + 2, 6))
    prev.convert('RGB').save('/tmp/npc_preview.png')
    print('预览: /tmp/npc_preview.png')
