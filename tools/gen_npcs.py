def head(p, y0=3, hw=12, hh=11, skin=SKIN, cx=16):
    """圆润头型：cx 为中心，返回 (x0,x1,y0,y1)"""
    x0, x1 = cx - hw // 2, cx + hw // 2 - 1
    y1 = y0 + hh - 1
    p.E(x0, y0, x1, y1, skin)
    p.R(x0 + 1, y0, x1 - 1, y1, skin)
    # 下颌收窄 + 右侧背光
    p.P(x0, y1 - 1, skin); p.P(x1, y1 - 1, skin)
    p.line([(x1, y0 + 2), (x1, y1 - 2)], shade(skin, 0.9))
    p.line([(x1 - 1, y0 + 1), (x1 - 1, y1 - 1)], shade(skin, 0.96))
    p.line([(x0 + 1, y0 + 1), (x0 + 2, y0 + 1)], SKIN_L)
    return (x0, x1, y0, y1)

def face(p, x0, x1, ey, skin=SKIN, big=False, eye_c=EYED, brow_c=None, mouth=None, blush=None):
    """眼睛（含高光）+ 眉 + 嘴 + 腮红"""
    lw = 3 if big else 2
    for ex in (x0 + 3, x1 - 3 - lw + 1):
        p.R(ex, ey, ex + lw - 1, ey + (2 if big else 1), eye_c)
        p.P(ex + lw - 1, ey, WHITE)                       # 高光
        p.P(ex, ey + (2 if big else 1), shade(eye_c, 1.6))
    if brow_c:
        p.line([(x0 + 3, ey - 2), (x0 + 4, ey - 2)], brow_c)
        p.line([(x1 - 4, ey - 2), (x1 - 3, ey - 2)], brow_c)
    if mouth:
        mx = (x0 + x1) // 2
        p.P(mx - 1, mouth, mouth_c if False else mouth[0])
        p.P(mx, mouth[0] if isinstance(mouth, tuple) else mouth, (0, 0, 0)) if False else None
    if blush:
        p.P(x0 + 1, ey + 2, blush); p.P(x0 + 2, ey + 2, blush)
        p.P(x1 - 1, ey + 2, blush); p.P(x1 - 2, ey + 2, blush)

def mouth(p, x0, x1, y, c=(178, 96, 84), smile=True):
    mx = (x0 + x1) // 2
    if smile:
        p.P(mx - 1, y - 1, c); p.P(mx, y - 1, c); p.P(mx - 2, y, c); p.P(mx + 1, y, c)
    else:
        p.R(mx - 1, y, mx, y, c)

def robe(p, y0, y1, c, hw_top=5, hw_bot=8, cx=16, fold=True):
    """钟形长袍：x0..x1 随 y 展开，返回底边"""
    x0t, x1t = cx - hw_top, cx + hw_top - 1
    x0b, x1b = cx - hw_bot, cx + hw_bot - 1
    p.poly([(x0t, y0), (x1t, y0), (x1b, y1), (x0b, y1)], c)
    # 左前受光带
    p.poly([(x0t, y0), (x0t + 1, y0), (x0b + 1, y1), (x0b, y1)], shade(c, 1.12))
    # 右侧背光
    p.poly([(x1t - 1, y0), (x1t, y0), (x1b, y1), (x1b - 1, y1)], shade(c, 0.78))
    # 底边压暗
    p.R(x0b, y1, x1b, y1, shade(c, 0.62))
    if fold:
        p.line([(cx - 2, y0 + 3), (cx - 4, y1 - 2)], shade(c, 0.82))
        p.line([(cx + 3, y0 + 3), (cx + 5, y1 - 2)], shade(c, 0.85))
    return (x0b, x1b, y1)

def feet(p, x0b, x1b, y1, c=(74, 56, 44), gap=4):
    p.R(x0b + 1, y1 + 1, x0b + gap, y1 + 2, c)
    p.R(x1b - gap, y1 + 1, x1b - 1, y1 + 2, c)

